const { test } = require('node:test');
const assert = require('node:assert/strict');
const { fixture } = require('./helpers.cjs');

test('legacy generated notes remain filterable after migration cleared their flags', async () => {
  const {q,sqlite,close}=await fixture(db => {
    db.exec("INSERT INTO notes(scope,date_key,title,content,is_auto_generated) VALUES ('daily','2026-09-28','Reflection','Completed 2/3 tasks today. Logged 4 units of progress. 1 task carried over from before.',1)");
    db.exec("INSERT INTO notes(scope,date_key,title,content,is_auto_generated) VALUES ('weekly','2026-09-28','Summary','2/3 tasks completed (67%). 2 cumulative days of carryover across tasks. Best habit streak: 7.',1)");
    db.exec("INSERT INTO notes(scope,date_key,title,content,is_auto_generated) VALUES ('daily','2026-09-28','Reflection','My own writing',0)");
  });
  const rows=await q.getAllNotesSummaries();
  assert.equal(rows.filter(n=>!n.isAutoGenerated).length,1);
  assert.equal(rows.find(n=>n.content==='My own writing').isAutoGenerated,false);
  assert.equal((await q.getNotesForScope('daily','2026-09-28')).filter(n=>n.isAutoGenerated).length,1);
  // Classification is non-destructive: preserve original text and records.
  assert.equal(sqlite.prepare('select count(*) n from notes').get().n,3);
  close();
});

test('renaming or linking a snapshot preserves its origin; personal edits become reflections',async()=>{
  const {q,close}=await fixture();
  const content='2/3 scheduled task records completed.\nThis is a snapshot; later changes do not rewrite saved reflections.';
  const note=await q.createNote('daily','2026-10-24',content,'Snapshot',true);
  const pursuit=await q.insertPursuit({title:'Reading'});
  await q.updateNoteDetails(note.id,{title:'Reading summary',content,pursuitId:pursuit.id});
  assert.equal((await q.getAllNotesSummaries())[0].isAutoGenerated,true);
  await q.updateNoteContent(note.id,content);
  assert.equal((await q.getAllNotesSummaries())[0].isAutoGenerated,true);
  await q.updateNoteContent(note.id,content+'\nI enjoyed the last chapter.');
  assert.equal((await q.getAllNotesSummaries())[0].isAutoGenerated,false);
  close();
});

