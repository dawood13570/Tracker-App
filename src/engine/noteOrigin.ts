/** Recover only complete, known legacy summary templates. Titles never determine origin. */
export function isGeneratedNote(note: { isAutoGenerated: boolean; content: string | null }): boolean {
  if (note.isAutoGenerated) return true;
  const content = note.content?.trim() ?? '';
  const daily = /^Completed \d+\/\d+ tasks? today\.(?: Logged \d+(?:\.\d+)? units? of progress\.)?(?: \d+ tasks? carried over from before\.)?$/;
  const period = /^\d+\/\d+ tasks? completed \(\d+%\)\.(?: \d+ cumulative days? of carryover across tasks\.)?(?: Best habit streak: \d+\.)?$/;
  const snapshot = /^\d+\/\d+ scheduled task records completed\.(?:\nProgress recorded: [^\n]+\.)?(?:\n\d+ carryover events?\.)?\nThis is a snapshot; later changes do not rewrite saved reflections\.$/;
  return daily.test(content) || period.test(content) || snapshot.test(content);
}
export function withNoteOrigin<T extends { isAutoGenerated: boolean; content: string | null }>(note: T): T {
  return { ...note, isAutoGenerated: isGeneratedNote(note) };
}
